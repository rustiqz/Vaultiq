#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_params_clear_the_owasp_floor() {
        let params = Argon2Params::default();
        params.validate().unwrap();
        assert!(params.memory_kib >= MIN_MEMORY_KIB);
        assert!(params.iterations >= MIN_ITERATIONS);
    }

    #[test]
    fn weak_params_are_rejected() {
        let weak = Argon2Params {
            memory_kib: 1024,
            iterations: 1,
            parallelism: 0,
        };
        assert!(weak.validate().is_err());
    }

    #[test]
    fn generated_salts_differ() {
        let a = Salt::generate().unwrap();
        let b = Salt::generate().unwrap();
        assert_ne!(a, b, "two CSPRNG salts must not collide");
    }

    #[test]
    fn salt_round_trips_through_bytes() {
        let salt = Salt::generate().unwrap();
        let restored = Salt::from_bytes(salt.as_bytes()).unwrap();
        assert_eq!(salt, restored);
    }

    #[test]
    fn salt_rejects_wrong_length() {
        assert!(Salt::from_bytes(&[0u8; SALT_LEN - 1]).is_err());
        assert!(Salt::from_bytes(&[0u8; SALT_LEN + 1]).is_err());
    }

    #[test]
    fn master_key_debug_is_redacted() {
        let key = MasterKey::from_bytes([7u8; MASTER_KEY_LEN]);
        let rendered = format!("{key:?}");
        assert_eq!(rendered, "MasterKey([REDACTED])");
        assert!(!rendered.contains('7'));
    }
}
